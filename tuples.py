
numbers = (10, 20, 30, 20, 40, 77, 88, 20, 10)
print("Tuple:", numbers)
print("First element:", numbers[0])
print("Slicing:", numbers[1:4])
print("Start:", numbers[2:])
print("Stop:", numbers[:3])
print("Start, Stop, Step:", numbers[0:5:2])
print("Step 2:", numbers[::2])
print("Reverse:", numbers[::-1])
print("Count of 20:", numbers.count(20))
print("Index of 30:", numbers.index(30))
print("Length:", len(numbers))
print("Maximum:", max(numbers))
print("Minimum:", min(numbers))
print("Sum:", sum(numbers))
print("Sorted:", sorted(numbers))
print("20 in tuple:", 100 in numbers)
print("50 not in tuple:", 50 not in numbers)